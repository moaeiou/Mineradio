#!/usr/bin/env node
// Mineradio renderer bundle builder.
//
// Reads the ordered module list from public/js/index-loader.js, concatenates
// every module into a single classic script, then minifies it with terser when
// terser is available (falls back to a plain concatenation otherwise). The
// bundle is written to public/js/index.bundle.js and loaded by index-loader.js
// at runtime; the per-module sources stay in the repo for development and for
// scripts/quick-check.js, but are excluded from the packaged app.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(scriptDir, "..");
const publicDir = path.join(appRoot, "public");
const loaderPath = path.join(publicDir, "js", "index-loader.js");
const bundlePath = path.join(publicDir, "js", "index.bundle.js");

function fail(message) {
  console.error("[bundle-renderer] " + message);
  process.exit(1);
}

function readModulePaths() {
  const loader = fs.readFileSync(loaderPath, "utf8");
  const match = loader.match(/const modulePaths = \[([\s\S]*?)\];/);
  if (!match) fail("modulePaths not found in public/js/index-loader.js");
  const paths = [...match[1].matchAll(/["']([^"']+)["']/g)].map((m) => m[1]);
  if (!paths.length) fail("modulePaths is empty");
  return paths;
}

function concatenateModules(modulePaths) {
  const parts = [];
  const missing = [];
  for (const modulePath of modulePaths) {
    const absolute = path.join(publicDir, modulePath);
    if (!fs.existsSync(absolute)) {
      missing.push(modulePath);
      continue;
    }
    parts.push(fs.readFileSync(absolute, "utf8"));
  }
  if (missing.length) {
    fail("missing module files:\n  " + missing.join("\n  "));
  }
  return parts.join("\n");
}

async function minifyWithTerser(code) {
  let terser = null;
  try {
    terser = require("terser");
  } catch (e) {
    return { code, minified: false };
  }
  const result = await terser.minify(code, {
    compress: {
      passes: 2,
      pure_getters: false,
    },
    mangle: {
      // Inline onclick/oninput handlers in index.html reference top-level
      // functions; keep top-level names untouched.
      toplevel: false,
    },
    format: {
      comments: false,
    },
    keep_classnames: true,
    keep_fnames: true,
  });
  if (result.error) throw result.error;
  return { code: result.code, minified: true };
}

function validateBundle(code) {
  // Parse-only validation: catches syntax breakage before it ships. The code
  // is a classic browser script, so window/document references are fine here.
  new Function(code);
}

const modulePaths = readModulePaths();
const raw = concatenateModules(modulePaths);
const header =
  "/* Mineradio renderer bundle. Generated by scripts/bundle-renderer.mjs; do not edit. */\n";
let bundle = header + raw;
let minified = false;
try {
  const result = await minifyWithTerser(bundle);
  bundle = result.code;
  minified = result.minified;
} catch (error) {
  fail(
    "terser failed (" +
      (error && error.message) +
      "); the unminified bundle was NOT written.",
  );
}
validateBundle(bundle);

fs.writeFileSync(bundlePath, bundle, "utf8");

const rawKb = Math.round((raw.length / 1024) * 10) / 10;
const bundleKb = Math.round((bundle.length / 1024) * 10) / 10;
console.log(
  "[bundle-renderer] " +
    modulePaths.length +
    " modules -> " +
    path.relative(appRoot, bundlePath) +
    " (" +
    rawKb +
    " KB raw, " +
    bundleKb +
    " KB " +
    (minified ? "minified" : "concatenated, terser unavailable") +
    ")",
);
